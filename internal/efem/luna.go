// Luna devuelve la longitud eclíptica aparente de la Luna en grados. Meeus cap. 47.
func Luna(jd float64) float64 {
	t := T(jd)
	Lp := norm360(218.3164477 + 481267.88123421*t - 0.0015786*t*t +
		t*t*t/538841 - t*t*t*t/65194000)
	D := norm360(297.8501921 + 445267.1114034*t - 0.0018819*t*t +
		t*t*t/545868 - t*t*t*t/113065000)
	M := norm360(357.5291092 + 35999.0502909*t - 0.0001536*t*t + t*t*t/24490000)
	Mp := norm360(134.9633964 + 477198.8675055*t + 0.0087414*t*t +
		t*t*t/69699 - t*t*t*t/14712000)
	F := norm360(93.2720950 + 483202.0175233*t - 0.0036539*t*t -
		t*t*t/3526000 + t*t*t*t/863310000)
	E := 1 - 0.002516*t - 0.0000074*t*t

	// argumentos aditivos (Meeus p. 338)
	A1 := norm360(119.75 + 131.849*t)
	A2 := norm360(53.09 + 479264.290*t)

	var sl float64
	for _, x := range luna {
		arg := (float64(x.d)*D + float64(x.m)*M + float64(x.mp)*Mp + float64(x.f)*F) * Grados
		c := x.l
		switch {
		case x.m == 1 || x.m == -1:
			c *= E
		case x.m == 2 || x.m == -2:
			c *= E * E
		}
		sl += c * math.Sin(arg)
	}
	sl += 3958*math.Sin(A1*Grados) + 1962*math.Sin((Lp-F)*Grados) + 318*math.Sin(A2*Grados)

	dpsi, _ := Nutacion(jd)
	return norm360(Lp + sl/1e6 + dpsi)
}

// NodoLunarMedio devuelve la longitud del nodo norte medio (Rāhu) en grados.
func NodoLunarMedio(jd float64) float64 {
	t := T(jd)
	return norm360(125.0445479 - 1934.1362891*t + 0.0020754*t*t +
		t*t*t/467441 - t*t*t*t/60616000)
}
